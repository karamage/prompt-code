//! macOS の機能。クリップボードの監視と、ほかのアプリへの ⌘V。

use std::sync::atomic::{AtomicBool, Ordering};
use std::thread;
use std::time::Duration;

use core_foundation::base::TCFType;
use core_foundation::boolean::CFBoolean;
use core_foundation::dictionary::{CFDictionary, CFDictionaryRef};
use core_foundation::string::{CFString, CFStringRef};
use core_graphics::event::{CGEvent, CGEventFlags, CGEventTapLocation};
use core_graphics::event_source::{CGEventSource, CGEventSourceStateID};
use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
use objc2_foundation::NSString;

#[link(name = "ApplicationServices", kind = "framework")]
extern "C" {
    fn AXIsProcessTrusted() -> bool;
    fn AXIsProcessTrustedWithOptions(options: CFDictionaryRef) -> bool;
    static kAXTrustedCheckOptionPrompt: CFStringRef;
}

/// パスワードマネージャなどが「履歴に残さないで」と付ける印（nspasteboard.org の取り決め）
const SKIP_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// クリップボードを見張り、文字がコピーされるたびに on_copy を呼ぶ。
/// NSPasteboard には変化の知らせが無いので、変化の回数（changeCount）を短い間隔で見比べる
pub fn watch_clipboard(on_copy: impl Fn(String) + Send + 'static) {
    thread::spawn(move || {
        let mut last = change_count();
        loop {
            thread::sleep(Duration::from_millis(500));
            let count = change_count();
            if count == last {
                continue;
            }
            last = count;
            if let Some(text) = read_text() {
                on_copy(text);
            }
        }
    });
}

fn change_count() -> isize {
    NSPasteboard::generalPasteboard().changeCount()
}

/// クリップボードの文字。履歴に残さないよう印の付いたものや、文字でないものは None
fn read_text() -> Option<String> {
    let board = NSPasteboard::generalPasteboard();
    if let Some(types) = board.types() {
        for kind in types.iter() {
            let kind = kind.to_string();
            if SKIP_TYPES.contains(&kind.as_str()) {
                return None;
            }
        }
    }
    let text: Option<objc2::rc::Retained<NSString>> = board.stringForType(unsafe { NSPasteboardTypeString });
    text.map(|s| s.to_string())
}

/// ほかのアプリへキーを送るのに要る「アクセシビリティ」の許可があるか
pub fn is_trusted() -> bool {
    unsafe { AXIsProcessTrusted() }
}

static ASKED: AtomicBool = AtomicBool::new(false);

/// 許可が無ければ、システム設定へ案内するダイアログを 1 回だけ出す
fn ask_for_trust() {
    if ASKED.swap(true, Ordering::SeqCst) {
        return;
    }
    let key = unsafe { CFString::wrap_under_get_rule(kAXTrustedCheckOptionPrompt) };
    let options = CFDictionary::from_CFType_pairs(&[(key.as_CFType(), CFBoolean::true_value().as_CFType())]);
    unsafe { AXIsProcessTrustedWithOptions(options.as_concrete_TypeRef()) };
}

/// いま前面にあるアプリに ⌘V を送る。許可が無ければ送らず、許可を求める。送れたら true
pub fn send_paste() -> bool {
    if !is_trusted() {
        ask_for_trust();
        return false;
    }
    // V のキーコード
    const KEY_V: u16 = 9;
    let Ok(source) = CGEventSource::new(CGEventSourceStateID::CombinedSessionState) else {
        return false;
    };
    for down in [true, false] {
        if let Ok(event) = CGEvent::new_keyboard_event(source.clone(), KEY_V, down) {
            event.set_flags(CGEventFlags::CGEventFlagCommand);
            event.post(CGEventTapLocation::HID);
        }
    }
    true
}
